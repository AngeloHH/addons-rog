<?php

/**
 * Addons ROG - Upload storage and media access
 *
 * - Validate uploaded files and store them under private random storage keys.
 * - Control media visibility and maintain expiry for submission attachments.
 */

declare(strict_types=1);

namespace Rog\Services;

use finfo;
use Rog\Http\{ApiException, Validator as V, Response};
use RuntimeException;
use Throwable;

class FileService extends Service {

    // =========================================================================
    // PRIVATE PATHS AND PUBLIC REFERENCES
    // =========================================================================

    /**
     * Resolve only storage keys generated by this application.
     */
    public function path(array $asset): string {
        $error = 'Invalid storage key';
        if (!preg_match('~^[a-f0-9]{2}/[a-f0-9]{64}$~D', $asset['storage_key'])) throw new RuntimeException($error);
        return $this->app->config['storage'] . '/objects/' . $asset['storage_key'];
    }

    public function url(array $asset): string {
        return $this->app->config['origin'] . '/api/files/' . $asset['external_id'];
    }

    // =========================================================================
    // UPLOAD VALIDATION AND STORAGE
    // =========================================================================

    public function store(array $file, string $kind): array {
        if (($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK) throw new ApiException(
            in_array($file['error'] ?? 4, [1, 2], true) ? 413 : 422, 'FILE_TOO_LARGE'
        );
        if (!is_uploaded_file($file['tmp_name'])) V::fail('file');
        $size = filesize($file['tmp_name']);
        $max = $kind === 'zip' ? 50 * 1024 * 1024 : ($kind === 'attachment' ? 10 * 1024 * 1024 : 2 * 1024 * 1024);
        if ($size < 1 || $size > $max) throw new ApiException(413, 'FILE_TOO_LARGE');

        // Inspect the uploaded contents instead of trusting the
        // browser-provided MIME type.
        $mime = (new finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']); $meta = []; $status = 'clean';
        $allowed = $kind === 'zip' ? ['application/zip', 'application/x-zip-compressed'] : ($kind === 'attachment'
            ? ['image/png', 'image/jpeg', 'image/webp', 'text/plain', 'application/pdf', 'application/zip']
            : ['image/png', 'image/jpeg', 'image/webp']);
        if (
            !in_array($mime, $allowed, true) || $mime === 'image/webp'
        ) throw new ApiException(415, 'UNSUPPORTED_MEDIA_TYPE');
        if ($mime === 'application/zip' || $kind === 'zip') {
            $meta = (new ZipScanner())->scan($file['tmp_name']); $status = $meta['status'];
        }
        if (in_array($kind, ['icon', 'screenshot'], true)) {
            $info = getimagesize($file['tmp_name']);
            if (!$info) V::fail('file');
            [$width, $height] = $info;
            if (
                ($kind === 'icon' && ($width !== 256 || $height !== 256))
                || ($kind === 'screenshot' && ($width < 640 || $height < 360 || $width > 3840 || $height > 2160))
            ) V::fail('file');
            $meta += ['width' => $width, 'height' => $height];
        }
        // Use a random private path; the original filename remains metadata.
        $key = bin2hex(random_bytes(32)); $key = substr($key, 0, 2) . '/' . $key;
        $path = $this->path(['storage_key' => $key]); $error = 'Cannot create storage';
        if (
            !is_dir(dirname($path)) && !mkdir(dirname($path), 0700, true) && !is_dir(dirname($path))
        ) throw new RuntimeException($error);
        if (!move_uploaded_file($file['tmp_name'], $path)) throw new RuntimeException('Cannot save upload');
        try {
            $query = 'INSERT INTO assets(owner_id,kind,storage_key,filename,mime_type,size_bytes,status,metadata,';
            $query .= "expires_at) VALUES (:owner,:kind,:key,:name,:mime,:size,:status,CAST(:meta AS jsonb),";
            $query .= "now()+interval '24 hours') RETURNING *";
            return $this->row($query, [
                'owner' => $this->user_id() ?: null, 'kind' => $kind, 'key' => $key,
                'name' => mb_substr(basename(str_replace('\\', '/', $file['name'])), 0, 200),
                'mime' => $mime, 'size' => $size, 'status' => $status, 'meta' => $this->encode((object)$meta),
            ]);
        // Remove the moved file if recording its metadata fails.
        } catch (Throwable $error) { unlink($path); throw $error; }
    }

    // =========================================================================
    // UPLOAD RESPONSE VALUES
    // =========================================================================

    public function present(array $asset): array {
        $meta = $this->json($asset['metadata']);
        if ($asset['kind'] === 'zip') return [
            'id' => $asset['external_id'], 'fileName' => $asset['filename'], 'size' => (int)$asset['size_bytes'],
            'status' => $asset['status'], 'expiresAt' => $this->date($asset['expires_at']),
        ] + $meta;
        return [
            'id' => (int)$asset['id'], 'kind' => $asset['kind'], 'url' => $this->url($asset),
            'width' => $meta['width'] ?? 0, 'height' => $meta['height'] ?? 0,
            'size' => (int)$asset['size_bytes'], 'expiresAt' => $this->date($asset['expires_at']),
        ];
    }

    public function upload(): array {
        $this->rate('upload:' . $this->user_id(), 30, 3600);
        $kind = $this->request->path === '/uploads' ? 'zip'
            : V::choice($this->request->input('kind'), 'kind', ['icon', 'screenshot']);
        $asset = $this->store($this->request->files['file'] ?? [], $kind);
        return [$kind === 'zip' ? 'upload' : 'media' => $this->present($asset)];
    }

    // =========================================================================
    // MEDIA VISIBILITY AND STREAMING
    // =========================================================================

    public function media(): Response {
        $query = "SELECT * FROM assets WHERE external_id::text=:id AND kind IN ('icon','screenshot','attachment') ";
        $query .= "AND status IN ('clean','warning') AND (expires_at IS NULL OR expires_at>now())";
        $asset = $this->row($query, ['id' => $this->request->param('fileId')]);
        // Contact attachments remain staff-only, even when their public UUID is
        // known.
        if ($asset['kind'] === 'attachment') {
            if (!$this->staff()) throw new ApiException(404, 'NOT_FOUND');
            $response = Response::stream($this->path($asset), $asset['filename'], $asset['mime_type']);
            $response->headers['Content-Security-Policy'] = "sandbox; default-src 'none'";
            return $response;
        }
        $query = 'SELECT EXISTS(SELECT 1 FROM asset_links l LEFT JOIN addons a ON a.id=l.addon_id ';
        $query .= 'LEFT JOIN published_versions v ON v.id=l.submission_id WHERE l.asset_id=:id ';
        $query .= 'AND ((a.id IS NOT NULL AND a.withdrawn_at IS NULL) OR v.id IS NOT NULL))';
        // Unpublished images are visible only to their owner or staff.
        $public = $this->db()->value($query, ['id' => $asset['id']]);
        if (
            !$public && (int)$asset['owner_id'] !== $this->user_id() && !$this->staff()
        ) throw new ApiException(404, 'NOT_FOUND');

        $response = Response::stream($this->path($asset), $asset['filename'], $asset['mime_type']);
        $response->headers['Content-Disposition'] = 'inline';
        $response->headers['Content-Security-Policy'] = "default-src 'none'";
        return $response;
    }

    // =========================================================================
    // SUBMISSION LINKS AND ASSET EXPIRY
    // =========================================================================

    public function linked(int $id): array {
        $query = 'SELECT a.*,l.slot,l.position FROM asset_links l JOIN assets a ON a.id=l.asset_id ';
        $query .= 'WHERE l.submission_id=:id ORDER BY l.slot,l.position';
        return $this->db()->all($query, ['id' => $id]);
    }

    /**
     * Keep retained assets indefinitely; draft-only assets follow the latest
     * linked draft expiry.
     */
    public function refresh_expiry(int $submission_id): void {
        $query = 'UPDATE assets AS a SET expires_at=CASE WHEN EXISTS(SELECT 1 FROM asset_links l ';
        $query .= 'LEFT JOIN submissions s ON s.id=l.submission_id WHERE l.asset_id=a.id ';
        $query .= "AND (l.addon_id IS NOT NULL OR l.message_id IS NOT NULL OR s.status<>'draft')) ";
        $query .= "THEN NULL ELSE (SELECT max(s.updated_at)+interval '30 days' FROM asset_links l ";
        $query .= 'JOIN submissions s ON s.id=l.submission_id WHERE l.asset_id=a.id) END ';
        $query .= 'WHERE EXISTS(SELECT 1 FROM asset_links t WHERE t.asset_id=a.id AND t.submission_id=:id)';
        $this->db()->query($query, ['id' => $submission_id]);
    }
}
